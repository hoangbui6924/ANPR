// Convert a photo into star-portrait data for hide.html
// Usage: node make-portrait.mjs <image> [output.points.js] [width]
// Removes the background, keeps the largest subject region and writes
// `window.PORTRAIT = {...}` (a classic script, so it also loads over file://).
import sharp from "sharp"; // same version as @imgly/background-removal-node uses (two copies clash on Windows)
import { removeBackground } from "@imgly/background-removal-node";
import fs from "fs";
import path from "path";
import { pathToFileURL } from "url";

const input = process.argv[2];
if (!input) {
    console.error("Usage: node make-portrait.mjs <image> [output.points.js] [width]");
    process.exit(1);
}
const output = process.argv[3] || input.replace(/\.[^.]+$/, "") + ".points.js";
const W = Math.min(parseInt(process.argv[4] || "240", 10), 255); // x is stored in one byte

console.log("Removing background...");
const blob = await removeBackground(pathToFileURL(path.resolve(input)).href, {
    model: "medium",
    output: { format: "image/png" }
});
const cutout = Buffer.from(await blob.arrayBuffer());

const { data, info } = await sharp(cutout).ensureAlpha().resize(W).raw().toBuffer({ resolveWithObject: true });
const H = info.height;
if (H > 65535) throw new Error("image too tall");

// Foreground mask, then keep only the largest connected region (drops stray specks / watermarks)
let mask = new Uint8Array(W * H);
for (let i = 0; i < W * H; i++) mask[i] = data[i * 4 + 3] > 128 ? 1 : 0;
let label = new Int32Array(W * H), best = 0, bestSize = 0, next = 1, stack = [];
for (let s = 0; s < W * H; s++) {
    if (!mask[s] || label[s]) continue;
    let size = 0;
    label[s] = next;
    stack.push(s);
    while (stack.length) {
        let i = stack.pop(), x = i % W, y = (i / W) | 0;
        size++;
        for (let [nx, ny] of [[x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]]) {
            if (nx < 0 || ny < 0 || nx >= W || ny >= H) continue;
            let j = ny * W + nx;
            if (mask[j] && !label[j]) { label[j] = next; stack.push(j); }
        }
    }
    if (size > bestSize) { bestSize = size; best = next; }
    next++;
}
for (let i = 0; i < W * H; i++) mask[i] = label[i] === best ? 1 : 0;

// Distance to the silhouette edge (chamfer 3-4) -> gentle 3D bulge
let dist = new Float32Array(W * H);
for (let i = 0; i < W * H; i++) dist[i] = mask[i] ? 1e9 : 0;
let at = (x, y) => (x < 0 || y < 0 || x >= W || y >= H) ? 0 : dist[y * W + x];
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    let i = y * W + x;
    if (!mask[i]) continue;
    dist[i] = Math.min(dist[i], at(x - 1, y) + 3, at(x, y - 1) + 3, at(x - 1, y - 1) + 4, at(x + 1, y - 1) + 4);
}
for (let y = H - 1; y >= 0; y--) for (let x = W - 1; x >= 0; x--) {
    let i = y * W + x;
    if (!mask[i]) continue;
    dist[i] = Math.min(dist[i], at(x + 1, y) + 3, at(x, y + 1) + 3, at(x + 1, y + 1) + 4, at(x - 1, y + 1) + 4);
}
let maxD = 1;
for (let i = 0; i < W * H; i++) if (mask[i]) maxD = Math.max(maxD, dist[i]);

// 7 bytes per point: x, y(lo), y(hi), depth, r, g, b
let bytes = [];
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    let i = y * W + x;
    if (!mask[i]) continue;
    let z = Math.round(Math.sqrt(dist[i] / maxD) * 255);
    bytes.push(x, y & 255, y >> 8, z, data[i * 4], data[i * 4 + 1], data[i * 4 + 2]);
}
const count = bytes.length / 7;
fs.writeFileSync(output,
    `// Generated by tools/make-portrait.mjs from ${path.basename(input)}\n` +
    `window.PORTRAIT = ${JSON.stringify({ width: W, height: H, count, data: Buffer.from(bytes).toString("base64") })};\n`);
console.log(`Wrote ${output}: ${count} points (${W}x${H})`);
